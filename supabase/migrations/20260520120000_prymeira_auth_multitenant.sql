declare
  next_configuration_id bigint;
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'configuration'
      and column_name = 'id'
      and identity_generation is null
  ) then
    select coalesce(max(id), 0) + 1 into next_configuration_id
    from public.configuration;

    execute format(
      'alter table public.configuration alter column id add generated by default as identity (start with %s)',
      greatest(next_configuration_id, 1)
    );
  end if;
end;
$$;

