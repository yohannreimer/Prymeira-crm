do $$
declare
  default_workspace_id constant uuid := '00000000-0000-0000-0000-000000000001'::uuid;
  tenant_table text;
begin
  alter table if exists public.sales drop constraint if exists sales_user_id_fkey;

  drop trigger if exists on_auth_user_created on auth.users;
  drop trigger if exists on_auth_user_updated on auth.users;
  drop function if exists public.handle_new_user();
  drop function if exists public.handle_update_user();
  drop function if exists public.get_user_id_by_email(text);

  foreach tenant_table in array array[
    'companies',
    'contacts',
    'contact_notes',
    'pipelines',
    'deals',
    'deal_notes',
    'leads',
    'sales',
    'sales_goals',
    'tags',
    'automation_runs',
    'proposal_templates',
    'proposal_template_items',
    'proposals',
    'proposal_items',
    'automation_rules',
    'tasks',
    'configuration',
    'favicons_excluded_domains'
  ]
  loop
    execute format('alter table public.%I add column if not exists workspace_id uuid', tenant_table);
    execute format('update public.%I set workspace_id = %L::uuid where workspace_id is null', tenant_table, default_workspace_id);
    execute format('alter table public.%I alter column workspace_id set not null', tenant_table);
    execute format(
      'create index if not exists %I on public.%I using btree (workspace_id)',
      tenant_table || '_workspace_id_idx',
      tenant_table
    );
  end loop;
end;
$$;

